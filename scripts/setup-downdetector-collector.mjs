import { generateKeyPairSync } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const privateKeyPath = join(root, ".env.downdetector.local");
const publicKeyPath = join(
  root,
  "supabase",
  "functions",
  "downdetector-snapshot",
  "collector-public-key.ts",
);
const extensionDirectory = join(root, "scripts", "downdetector-extension");
const extensionConfigPath = join(extensionDirectory, "collector-config.local.js");

function writeExtensionConfig(privateKeyBase64) {
  mkdirSync(extensionDirectory, { recursive: true });
  writeFileSync(
    extensionConfigPath,
    `export const COLLECTOR_PRIVATE_KEY = "${privateKeyBase64}";\n`,
    { encoding: "utf8", mode: 0o600 },
  );
}

if (
  !process.argv.includes("--force") &&
  (existsSync(privateKeyPath) || existsSync(publicKeyPath))
) {
  if (!existsSync(privateKeyPath) || !existsSync(publicKeyPath)) {
    throw new Error("O par de chaves está incompleto. Use --force para fazer uma rotação planejada.");
  }
  const privateKeyBase64 = readFileSync(privateKeyPath, "utf8").match(
    /^DOWNDETECTOR_COLLECTOR_PRIVATE_KEY=(.+)$/m,
  )?.[1];
  if (!privateKeyBase64) throw new Error("A chave privada local está inválida.");
  writeExtensionConfig(privateKeyBase64);
  console.log("Configuração local da extensão atualizada com a chave existente.");
  process.exit(0);
}

const { privateKey, publicKey } = generateKeyPairSync("ed25519");
const privateKeyBase64 = privateKey.export({ type: "pkcs8", format: "der" }).toString("base64");
const publicKeyBase64 = publicKey.export({ type: "spki", format: "der" }).toString("base64");

writeFileSync(
  privateKeyPath,
  `DOWNDETECTOR_COLLECTOR_PRIVATE_KEY=${privateKeyBase64}\n`,
  { encoding: "utf8", mode: 0o600 },
);
writeFileSync(
  publicKeyPath,
  `// Generated by scripts/setup-downdetector-collector.mjs. Public verification key only.\nexport const COLLECTOR_PUBLIC_KEY = "${publicKeyBase64}";\n`,
  "utf8",
);
writeExtensionConfig(privateKeyBase64);

console.log(
  "Chaves do coletor criadas. A chave privada ficou somente no arquivo local ignorado pelo Git.",
);
console.log("Publique novamente a função e carregue scripts/downdetector-extension no Chrome.");
